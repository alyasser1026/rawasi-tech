const STATUS_DOTS: Record<string, string> = {"🔴":"#be123c","🟢":"#047857","🟡":"#a16207","🟠":"#c2410c","🔵":"#1d4ed8","⚪":"#9ca3af"};

const normalize = (value: string) => value.replace(/[\uFE0F\uFE0E]/g, "").trim();

export function emojiIcon(value: string): LucideIcon | undefined {
  const key = normalize(value);
  return EMOJI_ICONS[key] || EMOJI_ICONS[[...key][0] ?? ""];
}

type PhiIconProps = { value?: ReactNode; size?: number; className?: string; color?: string };

/** Renders an icon given either a React node or a legacy emoji string. */
export default function PhiIcon({ value, size = 18, className, color }: PhiIconProps) {
  if (value === null || value === undefined || value === false || value === "") return null;
  if (typeof value !== "string") return <>{value}</>;
  const key = normalize(value);
  const dot = STATUS_DOTS[key];
  if (dot) return <span className={className} aria-hidden="true" style={{ display: "inline-block", width: Math.max(8, Math.round(size / 2)), height: Math.max(8, Math.round(size / 2)), borderRadius: "50%", background: dot, flexShrink: 0 }} />;
  const Icon = emojiIcon(key);
  if (Icon) return <Icon size={size} className={className} color={color} aria-hidden="true" />;
  return /\p{Extended_Pictographic}/u.test(key) ? null : <>{value}</>;
}
